"""
orcad/tcl_gen.py  --  Generate Tcl scripts for OrCAD Capture.

Mode A (stub + net alias): Place every part, draw a short stub off each pin end,
attach a net alias with the net name. Capture connects same-named nets on a page.
This is the robust default. No routing is needed.

Mode B (routed): Use original wire segments scaled to mils. Build only if Mode A
is stable and time permits.

CRITICAL: Every Tcl command here must come from a journaled Capture session.
Never invent commands. If a command is unknown, raise UnknownTclCommand.
See data/ref/NOTES.md for the authoritative list.

CLI:
    python -m orcad.tcl_gen in/design.json out/design.tcl
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, List, Optional

# ---- internal imports ----
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from core.models import DesignIR, ComponentIR, NetIR, PinIR, DesignInfo
from core.config import DEFAULT_CONFIG


class UnknownTclCommand(RuntimeError):
    """Raised when we would need a Tcl command not in the verified set."""
    pass


# ---------------------------------------------------------------------------
# Verified Tcl command templates
# ---------------------------------------------------------------------------
# These templates are derived from OrCAD Capture journaling.
# DO NOT ADD NEW COMMANDS without verifying them in a live journal session.
# Verified: PlacePart, SelectObject, EditProperties, EndCommand, PlaceNetAlias,
#           PlaceWire, SaveDesign, source.
# NOT verified: DrawWire (use PlaceWire instead)
# ---------------------------------------------------------------------------

TCL_HEADER = """\
# Auto-generated by Schematic2DSN tcl_gen.py
# DO NOT EDIT - regenerate from design.json
set ErrorActionPreference stop
"""

TCL_FOOTER = """\
# Save the design
SaveDesign
"""


def _comment(text: str) -> str:
    return f"# {text}"


def _place_part(x: int, y: int, library: str, symbol: str,
                rotation: int = 0, mirror: bool = False) -> str:
    """
    PlacePart journaled command.
    Rotation: 0=0deg, 1=90deg, 2=180deg, 3=270deg (Capture convention).
    Mirror: MirrorX mirrors horizontally.
    NOTE: Verify exact argument order from journal before demo.
    """
    rot_idx = {0: 0, 90: 1, 180: 2, 270: 3}.get(rotation, 0)
    mirror_str = "MirrorX" if mirror else ""
    # Journal-derived form (verify on Day 0):
    # PlacePart x y LibraryPath SymbolName ?Rotation? ?Mirror?
    if mirror_str:
        return f"PlacePart {x} {y} {library} {symbol} {rot_idx} {mirror_str}"
    return f"PlacePart {x} {y} {library} {symbol} {rot_idx}"


def _set_refdes(refdes: str) -> str:
    """Set Reference property right after PlacePart. Journaled form."""
    # Journal-derived (verify on Day 0):
    return f'EditProperties Reference "{refdes}"'


def _set_value(value: str) -> str:
    """Set Value property right after PlacePart. Journaled form."""
    return f'EditProperties Value "{value}"'


def _end_command() -> str:
    """End the current interactive command."""
    return "EndCommand"


def _place_wire(x0: int, y0: int, x1: int, y1: int) -> str:
    """
    Draw an orthogonal wire segment.
    IMPORTANT: Only horizontal or vertical segments.
    Verify that PlaceWire accepts two endpoints in one call (journal).
    """
    if x0 != x1 and y0 != y1:
        raise ValueError(
            f"Non-orthogonal wire: ({x0},{y0})->({x1},{y1}). "
            "Only H/V wires are supported."
        )
    return f"PlaceWire {x0} {y0} {x1} {y1}"


def _place_net_alias(x: int, y: int, net_name: str, rotation: int = 0) -> str:
    """
    Place a net alias (power/signal name label) at (x, y).
    The wire end must be at the same point.
    Verify exact form from journal.
    """
    return f'PlaceNetAlias {x} {y} "{net_name}" {rotation}'


def _select_object(x: int, y: int) -> str:
    """Select the object at (x, y) -- used to select freshly placed parts."""
    return f"SelectObject {x} {y} 0"


# ---------------------------------------------------------------------------
# Tcl generation
# ---------------------------------------------------------------------------

def _snap(value: float, grid: int = 100) -> int:
    """Snap a mil value to the Capture grid."""
    return round(value / grid) * grid


def generate_mode_a(ir: DesignIR, lib_path: str, output_path: Optional[str] = None) -> str:
    """
    Generate Mode A Tcl: place parts + net alias stubs.

    For each component:
      1. PlacePart at snapped coordinates
      2. Set refdes and value
      3. For each pin, draw a stub wire off the pin end
      4. Place a net alias at the stub end

    Parameters
    ----------
    ir : DesignIR
        The intermediate representation.
    lib_path : str
        Path to the .olb library file for Capture to find symbols.
    output_path : str, optional
        If given, write the Tcl to this file.

    Returns
    -------
    str
        The complete Tcl script.
    """
    cfg = DEFAULT_CONFIG.orcad
    stub = cfg.stub_length_mils
    grid = cfg.grid_mils
    lines: List[str] = [TCL_HEADER]

    # Load symbol library map
    map_path = Path(__file__).parent / "symbol_map.json"
    with open(map_path) as f:
        sym_map = json.load(f)["map"]

    lines.append(_comment(f"Design: {ir.design.name}"))
    lines.append(_comment(f"Components: {len(ir.components)}, Nets: {len(ir.nets)}"))
    lines.append("")

    for comp in ir.components:
        sym_info = sym_map.get(comp.symbol_class)
        if sym_info is None:
            raise UnknownTclCommand(
                f"ERROR:NO_SYMBOL_MAP code=NO_LIBRARY_MAPPING "
                f"component={comp.id} class={comp.symbol_class}"
            )
        library = sym_info["library"]
        symbol = sym_info["symbol"]

        cx = _snap(comp.position.x, grid)
        cy = _snap(comp.position.y, grid)

        lines.append(_comment(f"--- {comp.id} ({comp.symbol_class}) value={comp.value} ---"))
        lines.append(_place_part(cx, cy, library, symbol, comp.rotation, comp.mirror))
        lines.append(_select_object(cx, cy))
        lines.append(_set_refdes(comp.id))
        if comp.value:
            lines.append(_set_value(comp.value))
        lines.append(_end_command())
        lines.append("")

        # Mode A: draw stubs and net aliases for each pin
        for pin in comp.pins:
            if pin.net is None:
                continue
            px = _snap(pin.pos.x, grid)
            py = _snap(pin.pos.y, grid)

            # Determine stub direction: away from component center
            dx = px - cx
            dy = py - cy

            if dx != 0 or dy != 0:
                # Extend in the dominant direction
                if abs(dx) >= abs(dy):
                    stub_end_x = px + (stub if dx > 0 else -stub)
                    stub_end_y = py
                else:
                    stub_end_x = px
                    stub_end_y = py + (stub if dy > 0 else -stub)
            else:
                # Fallback: stub right
                stub_end_x = px + stub
                stub_end_y = py

            stub_end_x = _snap(stub_end_x, grid)
            stub_end_y = _snap(stub_end_y, grid)

            lines.append(_comment(f"  pin {pin.number} ({pin.function}) -> {pin.net}"))
            lines.append(_place_wire(px, py, stub_end_x, stub_end_y))
            lines.append(_place_net_alias(stub_end_x, stub_end_y, pin.net))
            lines.append(_end_command())

        lines.append("")

    lines.append(TCL_FOOTER)
    script = "\n".join(lines)

    if output_path:
        Path(output_path).write_text(script, encoding="utf-8")

    return script


def generate_mode_b(
    ir: DesignIR,
    wires_file: Optional[str] = None,
    lib_path: str = "COMPETITION.olb",
    output_path: Optional[str] = None
) -> str:
    """
    Generate Mode B Tcl: places parts and routes orthogonal wire segments directly
    between pin ends and junctions using coordinate transformed paths.
    """
    cfg = DEFAULT_CONFIG.orcad
    grid = cfg.grid_mils
    lines: List[str] = [TCL_HEADER]

    map_path = Path(__file__).parent / "symbol_map.json"
    with open(map_path) as f:
        sym_map = json.load(f)["map"]

    lines.append(_comment(f"Design: {ir.design.name} (Mode B Routed)"))
    lines.append(_comment(f"Components: {len(ir.components)}, Nets: {len(ir.nets)}"))
    lines.append("")

    # 1. Place all parts
    for comp in ir.components:
        sym_info = sym_map.get(comp.symbol_class)
        if sym_info is None:
            raise UnknownTclCommand(
                f"ERROR:NO_SYMBOL_MAP code=NO_LIBRARY_MAPPING "
                f"component={comp.id} class={comp.symbol_class}"
            )
        library = sym_info["library"]
        symbol = sym_info["symbol"]

        cx = _snap(comp.position.x, grid)
        cy = _snap(comp.position.y, grid)

        lines.append(_comment(f"--- {comp.id} ({comp.symbol_class}) ---"))
        lines.append(_place_part(cx, cy, library, symbol, comp.rotation, comp.mirror))
        lines.append(_select_object(cx, cy))
        lines.append(_set_refdes(comp.id))
        if comp.value:
            lines.append(_set_value(comp.value))
        lines.append(_end_command())

    lines.append("")
    lines.append(_comment("--- Routed Wire Connections ---"))

    # 2. Connect pins belonging to the same net with orthogonal segments
    drawn_wires: set = set()
    for net in ir.nets:
        # Collect all pin positions for this net
        net_pin_positions = []
        for pref in net.pins:
            c_id, p_num = pref[0], pref[1]
            for c in ir.components:
                if c.id == c_id:
                    for p in c.pins:
                        if p.number == p_num:
                            net_pin_positions.append((_snap(p.pos.x, grid), _snap(p.pos.y, grid)))

        # Draw connecting orthogonal wires between sequential pin endpoints
        if len(net_pin_positions) >= 2:
            lines.append(_comment(f"Net: {net.name}"))
            for i in range(len(net_pin_positions) - 1):
                p0 = net_pin_positions[i]
                p1 = net_pin_positions[i + 1]
                if p0 == p1:
                    continue

                # Ensure orthogonality: route via L-bend if needed
                if p0[0] != p1[0] and p0[1] != p1[1]:
                    # Corner point
                    corner = (p1[0], p0[1])
                    seg1 = (min(p0, corner), max(p0, corner))
                    seg2 = (min(corner, p1), max(corner, p1))
                    if seg1 not in drawn_wires:
                        lines.append(_place_wire(p0[0], p0[1], corner[0], corner[1]))
                        drawn_wires.add(seg1)
                    if seg2 not in drawn_wires:
                        lines.append(_place_wire(corner[0], corner[1], p1[0], p1[1]))
                        drawn_wires.add(seg2)
                else:
                    seg = (min(p0, p1), max(p0, p1))
                    if seg not in drawn_wires:
                        lines.append(_place_wire(p0[0], p0[1], p1[0], p1[1]))
                        drawn_wires.add(seg)

            # Place a net label at the first pin endpoint
            lbl_pos = net_pin_positions[0]
            lines.append(_place_net_alias(lbl_pos[0], lbl_pos[1], net.name))
            lines.append(_end_command())

    lines.append(TCL_FOOTER)
    script = "\n".join(lines)

    if output_path:
        Path(output_path).write_text(script, encoding="utf-8")

    return script


def load_ir(path: str) -> DesignIR:
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return DesignIR.model_validate(data)



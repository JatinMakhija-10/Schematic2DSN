def make_demo_ir() -> DesignIR:
    """
    Hand-built IR for Day 0 testing:
      R1 10k between VCC and NET_001
      C1 100nF between NET_001 and GND
    Positions are in mils, Capture coordinate system.
    """
    from core.models import (
        DesignIR, DesignInfo, ComponentIR, PinIR, NetIR, LabelIR,
        WarningIR, DesignMetadata, Point
    )

    r1 = ComponentIR(
        id="R1", symbol_class="RESISTOR", value="10k",
        unit=1, position=Point(x=4200, y=3000),
        rotation=0, mirror=False,
        confidence=1.0,
        pins=[
            PinIR(number="1", function="A",
                  pos=Point(x=4100, y=3000), net="VCC"),
            PinIR(number="2", function="B",
                  pos=Point(x=4300, y=3000), net="NET_001"),
        ]
    )

    c1 = ComponentIR(
        id="C1", symbol_class="CAPACITOR", value="100nF",
        unit=1, position=Point(x=4700, y=3000),
        rotation=0, mirror=False,
        confidence=1.0,
        pins=[
            PinIR(number="1", function="PLUS",
                  pos=Point(x=4600, y=3000), net="NET_001"),
            PinIR(number="2", function="MINUS",
                  pos=Point(x=4800, y=3000), net="GND"),
        ]
    )

    vcc1 = ComponentIR(
        id="VCC1", symbol_class="VCC", value="",
        unit=1, position=Point(x=4000, y=3200),
        rotation=0, mirror=False,
        confidence=1.0,
        pins=[
            PinIR(number="1", function="PWR",
                  pos=Point(x=4000, y=3100), net="VCC"),
        ]
    )

    gnd1 = ComponentIR(
        id="GND1", symbol_class="GROUND", value="",
        unit=1, position=Point(x=5000, y=2800),
        rotation=0, mirror=False,
        confidence=1.0,
        pins=[
            PinIR(number="1", function="PWR",
                  pos=Point(x=5000, y=2900), net="GND"),
        ]
    )

    net_vcc = NetIR(
        name="VCC", auto_named=False,
        pins=[["R1", "1"], ["VCC1", "1"]],
        labels=[LabelIR(text="VCC", pos=Point(x=4000, y=3200))]
    )

    net_001 = NetIR(
        name="NET_001", auto_named=True,
        pins=[["R1", "2"], ["C1", "1"]],
    )

    net_gnd = NetIR(
        name="GND", auto_named=False,
        pins=[["C1", "2"], ["GND1", "1"]],
        labels=[LabelIR(text="GND", pos=Point(x=5000, y=2800))]
    )

    return DesignIR(
        schema_version="1.0",
        design=DesignInfo(name="demo_RC", page=1, units="mils", grid=100),
        components=[r1, c1, vcc1, gnd1],
        nets=[net_vcc, net_001, net_gnd],
        warnings=[],
        metadata=DesignMetadata(
            source="hand-built",
            mode="vector",
            confidence=1.0,
            ocr_confidence=1.0,
        )
    )



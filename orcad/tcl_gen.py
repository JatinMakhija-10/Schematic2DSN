def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate OrCAD Capture Tcl script from design IR (Mode A)."
    )
    parser.add_argument(
        "input", nargs="?",
        help="Path to design.json. Omit to use the built-in demo IR."
    )
    parser.add_argument(
        "output", nargs="?", default="out/design.tcl",
        help="Output .tcl path (default: out/design.tcl)"
    )
    parser.add_argument(
        "--lib", default="orcad/library/COMPETITION.olb",
        help="Path to the .olb library file"
    )
    parser.add_argument(
        "--demo", action="store_true",
        help="Use built-in demo IR (R1+C1+GND+VCC) regardless of input"
    )
    parser.add_argument(
        "--dump-ir", action="store_true",
        help="Dump the IR JSON to stdout and exit"
    )
    args = parser.parse_args()

    if args.demo or args.input is None:
        ir = make_demo_ir()
    else:
        ir = load_ir(args.input)

    if args.dump_ir:
        print(ir.model_dump_json(indent=2))
        return

    Path(args.output).parent.mkdir(parents=True, exist_ok=True)
    script = generate_mode_a(ir, lib_path=args.lib, output_path=args.output)

    print(f"[tcl_gen] Wrote {len(script.splitlines())} lines -> {args.output}")
    print(f"[tcl_gen] Components: {len(ir.components)}, Nets: {len(ir.nets)}")


if __name__ == "__main__":
    main()
